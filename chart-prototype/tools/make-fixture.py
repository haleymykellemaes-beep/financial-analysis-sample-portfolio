#!/usr/bin/env python3
"""Regenerate chart-prototype/ohlcv-fixture.js.

The output is a fixed, synthetic OHLCV series for design review. It is NOT
market data. The path follows hand-placed anchor prices (so the shape suits the
hero composition) with seeded noise around them, then is written out as
literal values so the preview never computes data at load time.

    python3 chart-prototype/tools/make-fixture.py > chart-prototype/ohlcv-fixture.js
"""
import datetime as dt
import math
import random
import sys

SEED = 7
N = 240
LAST_DAY = dt.date(2026, 11, 18)

# (candles back from the latest, target price). Linear between anchors.
ANCHORS = [
    (239, 128), (205, 137), (172, 131), (150, 124), (128, 108),
    (116, 103), (110, 104), (86, 124), (70, 131), (56, 125),
    (36, 139), (19, 147), (9, 143), (0, 152),
]


def target(back):
    for (k0, p0), (k1, p1) in zip(ANCHORS, ANCHORS[1:]):
        if k1 <= back <= k0:
            f = (k0 - back) / (k0 - k1)
            return p0 + (p1 - p0) * f
    return ANCHORS[-1][1]


def business_days(end, count):
    days = []
    d = end
    while len(days) < count:
        if d.weekday() < 5:
            days.append(d)
        d -= dt.timedelta(days=1)
    return list(reversed(days))


def main(seed):
    rng = random.Random(seed)
    dates = business_days(LAST_DAY, N)
    err = 0.0
    prev_close = target(N - 1)
    rows = []
    for i, day in enumerate(dates):
        back = N - 1 - i
        slope = target(max(back - 1, 0)) / target(back) - 1
        err = 0.86 * err + 0.0115 * rng.gauss(0, 1)
        close = target(back) * math.exp(err)
        open_ = prev_close * math.exp(0.0035 * rng.gauss(0, 1))
        hi = max(open_, close) * math.exp(abs(rng.gauss(0, 0.0065)) + 0.0012)
        lo = min(open_, close) * math.exp(-abs(rng.gauss(0, 0.0065)) - 0.0012)
        ret = abs(close / prev_close - 1)
        trend = 1.25 if slope > 0.004 else 1.0
        vol = 1_850_000 * math.exp(0.28 * rng.gauss(0, 1)) * (1 + 16 * ret) * trend
        rows.append((day.isoformat(), open_, hi, lo, close, int(round(vol, -3))))
        prev_close = close

    out = sys.stdout
    out.write("/*\n")
    out.write(" * ILLUSTRATIVE OHLCV FIXTURE: synthetic data for design review only.\n")
    out.write(" * Not real market prices. \"DEMO\" is a fictitious symbol.\n")
    out.write(f" * {N} daily candles (weekdays), {dates[0].isoformat()} to {dates[-1].isoformat()}.\n")
    out.write(" * Fields: t = date, o/h/l/c = open/high/low/close, v = volume.\n")
    out.write(f" * Generated by tools/make-fixture.py (seed {seed}); values are stored literally.\n")
    out.write(" */\n")
    out.write("window.OHLCV_FIXTURE = {\n")
    out.write("  meta: {\n")
    out.write("    label: \"Illustrative OHLCV fixture (synthetic, not market data)\",\n")
    out.write("    symbol: \"DEMO\",\n")
    out.write("    interval: \"1D\",\n")
    out.write("  },\n")
    out.write("  candles: [\n")
    for t, o, h, l, c, v in rows:
        out.write(f"    {{ t: \"{t}\", o: {o:.2f}, h: {h:.2f}, l: {l:.2f}, c: {c:.2f}, v: {v} }},\n")
    out.write("  ],\n};\n")


if __name__ == "__main__":
    main(int(sys.argv[1]) if len(sys.argv) > 1 else SEED)
