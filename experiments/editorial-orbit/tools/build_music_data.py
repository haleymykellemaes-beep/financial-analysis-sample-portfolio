"""Build music/music-data.js from the Music app's library export.

    python3 build_music_data.py <Library.xml> <music/analysis.sql> <music/music-data.js>

1. Load the export into an in-memory SQLite table, tracks: analytical columns only
   (no file paths, persistent IDs or playlist names).
2. Run each named block in analysis.sql.
3. Write the SQL text and the result rows to music-data.js for the page.
Only these aggregates and top-10 lists are published, never the library itself.
"""
import json
import plistlib
import re
import sqlite3
import sys
from datetime import datetime, timezone


def load(path):
    lib = plistlib.load(open(path, "rb"))
    db = sqlite3.connect(":memory:")
    db.execute("""CREATE TABLE tracks (track_id INTEGER PRIMARY KEY, name TEXT, artist TEXT, album TEXT,
        genre TEXT, year INTEGER, duration_ms INTEGER, play_count INTEGER, skip_count INTEGER,
        date_added TEXT, last_played TEXT, loved INTEGER)""")
    iso = lambda d: d.strftime("%Y-%m-%dT%H:%M:%SZ") if d else None
    db.executemany("INSERT INTO tracks VALUES (?,?,?,?,?,?,?,?,?,?,?,?)", [
        (t["Track ID"], t.get("Name"), t.get("Artist"), t.get("Album"), t.get("Genre"), t.get("Year"),
         t.get("Total Time"), t.get("Play Count", 0), t.get("Skip Count", 0), iso(t.get("Date Added")),
         iso(t.get("Play Date UTC")), int(bool(t.get("Loved") or t.get("Favorited"))))
        for t in lib["Tracks"].values()])
    return db, lib.get("Date")


def main(xml, sql_path, out):
    db, exported = load(xml)
    blocks = re.split(r"^-- name: (\w+)\s*$", open(sql_path).read(), flags=re.M)[1:]
    queries = {}
    for name, body in zip(blocks[::2], blocks[1::2]):
        sql = body.strip()
        cur = db.execute(sql) if not sql.upper().lstrip("- \n").startswith("CREATE") else db.executescript(sql)
        cols = [c[0] for c in cur.description] if cur.description else []
        queries[name] = {"sql": sql, "columns": cols, "rows": [list(r) for r in cur.fetchall()] if cols else []}
    data = {"exported": exported.strftime("%Y-%m-%d") if exported else None,
            "built": datetime.now(timezone.utc).strftime("%Y-%m-%d"), "queries": queries}
    with open(out, "w") as f:
        f.write("/* Generated by tools/build_music_data.py from the Apple Music library export. Do not edit. */\n")
        f.write("window.MUSIC_DATA = " + json.dumps(data, ensure_ascii=False, indent=1) + ";\n")
    print("wrote", out, {k: len(v["rows"]) for k, v in queries.items()})


if __name__ == "__main__":
    main(*sys.argv[1:4])
